def add_shell_with_meshpy(  # noqa: D417
    knt0: np.ndarray,
    ijk0: np.ndarray,
    layers: int,
    K: float,
    beta: float,
    center: tuple[float, float, float],
    h0: float | None,
    hmax: float | None,
    minratio: float,
    max_steiner: int | None,
    no_exact: bool,
    verbose: bool,
    same_scaling: bool,
    shell_type: str = "box",
) -> tuple[np.ndarray, np.ndarray]:
    """Invoke TetGen to mesh exterior shell layers and merge with the body.

    Args:
        knt0 (np.ndarray): Body nodes.
        ijk0 (np.ndarray): Body connectivity.
        layers (int): Number of shell layers.
        K (float): Geometric factor.
        beta (float): Size scaling exponent.
        center (tuple[float, float, float]): Ray origin.
        h0 (float | None): Target edge length at interface.
        hmax (float | None): Target edge length at boundary.
        minratio (float): TetGen quality constraint.
        max_steiner (int | None): Limit on Steiner points.
        no_exact (bool): Suppress exact arithmetic.
        verbose (bool): Verbose logging.
        same_scaling (bool): Use linear size scaling.

    Returns:
        tuple[np.ndarray, np.ndarray]: (Merged nodes, Merged connectivity).
    """
    # Ensure we have mat_id column
    if ijk0.shape[1] >= 5:
        body_mat = int(ijk0[:, 4].max())
        ijk_body = ijk0[:, :5].astype(np.int32)
    else:
        body_mat = 1
        ijk_body = np.hstack(
            [
                ijk0[:, :4].astype(np.int32),
                np.full((ijk0.shape[0], 1), body_mat, dtype=np.int32),
            ]
        )
    shell_mat = body_mat + 1

    tris0 = find_outer_surface_tris(ijk_body)
    if tris0.size == 0:
        raise RuntimeError("Could not find outer surface triangles.")

    # PLC creation
    knt_plc, facets, seeds, surf_verts, node_map, svecs_layer = make_shell_plc_from_surface(
        knt0, tris0, layers=layers, K=K, center=center, shell_type=shell_type, target_h=h0
    )

    mi = MeshInfo()
    mi.set_points(knt_plc.tolist())
    mi.set_facets(facets)  # PLC facets (triangles)

    # Mesh only the *interior of shells* outside body: mark body interior as a hole
    body_centroid = np.mean(knt0[surf_verts], axis=0)
    mi.set_holes([tuple(body_centroid)])

    # ---- Per-layer size schedule ----
    if same_scaling:
        beta = 1.0

    if h0 is None:
        raise RuntimeError("Internal error: h0 must be resolved before calling add_shell_with_meshpy.")

    # New: drive h_layer_idx from the actual sv used for S_{layer_idx+1}
    gms = [float(np.exp(np.log(sv).mean())) for sv in svecs_layer]  # geometric means (length 'layers')

    if hmax is None:
        # Prevent explosion for large magnets with fine surface meshes (e.g. 200nm magnet with 2nm mesh)
        # by ensuring the outer elements are at least a fraction of the total airbox size.
        ext = np.max(knt0, axis=0) - np.min(knt0, axis=0)
        Lmax = float(np.max(ext))
        base_hmax = h0 * (gms[-1] ** beta)
        # Auto hmax: 20% of the core size scaled by KL
        auto_hmax = 0.2 * Lmax * gms[-1]
        resolved_hmax = max(base_hmax, auto_hmax)
    else:
        resolved_hmax = float(hmax)

    # ensure the *outermost* region hits the resolved hmax
    denom = max(h0 * (gms[-1] ** beta), 1e-30)
    scale = resolved_hmax / denom

    mi.regions.resize(layers)
    for layer_idx in range(layers):
        # region layer_idx is between S_layer_idx and S_{layer_idx+1}
        h_layer_idx = scale * h0 * (gms[layer_idx] ** beta)
        max_vol = approx_max_volume_from_edge(h_layer_idx)
        x, y, z = seeds[layer_idx]
        mi.regions[layer_idx] = (
            float(x),
            float(y),
            float(z),
            float(shell_mat),
            float(max_vol),
        )

    # TetGen options: PLC (-p), quality (-q), region attrs (-A), volume (-a)
    switches = "pqAaY"  # -Y preserve PLC facets
    opts = Options(switches)
    opts.minratio = float(minratio)
    opts.regionattrib = True
    opts.verbose = bool(verbose)
    if max_steiner is not None:
        opts.parse_switches(f"S{int(max_steiner)}")
    if no_exact:
        opts.parse_switches("X")

    shell = build(
        mi,
        options=opts,
        attributes=True,
        volume_constraints=True,
        verbose=bool(verbose),
    )
    knt_shell = np.asarray(shell.points, dtype=np.float64)
    tets_shell = np.asarray(shell.elements, dtype=np.int64)

    # Region attributes may be absent; in either case, set material id to shell_mat
    mat_shell = np.full(tets_shell.shape[0], shell_mat, dtype=np.int32)
    ijk_shell = np.hstack([tets_shell.astype(np.int32), mat_shell.reshape(-1, 1)])

    # Merge body + shell: append then weld
    knt_all = np.vstack([knt0, knt_shell])
    ijk_shell_shifted = ijk_shell.copy()
    ijk_shell_shifted[:, :4] += knt0.shape[0]
    ijk_merged = np.vstack([ijk_body, ijk_shell_shifted])

    knt_weld, ijk_weld, n_fused = weld_points(knt_all, ijk_merged, tol=1e-12)
    if n_fused:
        log(f"[validate] welded duplicate nodes: {n_fused}")

    ijk_weld[:, :4] = orient_tets_positive(knt_weld, ijk_weld[:, :4])
    ijk_weld = remove_degenerate_and_duplicate_tets(knt_weld, ijk_weld)
    return knt_weld, ijk_weld


# ----------------------------------------------------------------------
# Public entry point (importable) – pure in-memory (no writes)
# ----------------------------------------------------------------------
def run_add_shell_pipeline(  # noqa: D417
    *,
    in_npz: str,
    # Geometry controls
    layers: int | None = None,
    K: float | None = 1.5,
    KL: float | None = 10.0,
    auto_layers: bool = False,
    auto_K: bool = False,
    # Mesh-size coupling
    beta: float = 1.0,
    same_scaling: bool = False,
    # Radial center
    center: str | tuple[float, float, float] = "0,0,0",
    # Size targets
    h0: float | None = None,
    hmax: float | None = None,
    body_h: float | None = None,
    # TetGen options
    minratio: float = 1.4,
    max_steiner: int | None = None,
    no_exact: bool = False,
    verbose: bool = False,
    shell_type: str = "box",
) -> tuple[np.ndarray, np.ndarray]:
    """Programmatic entry point for adding graded shell layers.

    Args:
        in_npz (str): Path to input NPZ mesh.
        layers (int | None): Number of layers.
        K (float | None): Geometric factor.
        KL (float | None): Outermost geometric scale.
        auto_layers (bool): Derive layers from KL and K.
        auto_K (bool): Derive K from KL and layers.
        beta (float): Size coupling factor.
        same_scaling (bool): Use linear size scaling.
        center (str | tuple[float, float, float]): Ray origin.
        h0 (float | None): Size near body.
        hmax (float | None): Size at boundary.
        body_h (float | None): Override for body surface size.
        minratio (float): TetGen quality constraint.
        max_steiner (int | None): Limit on Steiner points.
        no_exact (bool): Suppress exact arithmetic.
        verbose (bool): Verbose logging.

    Returns:
        tuple[np.ndarray, np.ndarray]: (fused nodes, fused connectivity).
    """
    # Load input
    data = np.load(in_npz)
    if "knt" not in data or "ijk" not in data:
        raise KeyError("Input NPZ must contain 'knt' and 'ijk'.")
    knt0 = data["knt"].astype(np.float64)
    ijk0 = data["ijk"].astype(np.int64)

    # Center parsing (supports str "cx,cy,cz" or tuple)
    if isinstance(center, str):
        cx, cy, cz = parse_csv3(center)
    else:
        cx, cy, cz = (float(center[0]), float(center[1]), float(center[2]))

    # Ensure we have a mat_id column for surface processing where needed
    if ijk0.shape[1] >= 5:
        ijk_body = ijk0[:, :5].astype(np.int32)
    else:
        ijk_body = np.hstack([ijk0[:, :4].astype(np.int32), np.ones((ijk0.shape[0], 1), dtype=np.int32)])  # dummy mat

    # ---- Determine geometry triplet (L, K, KL) based on flags ----
    if auto_layers and auto_K:
        raise ValueError("Choose only one: auto_layers or auto_K.")

    L = layers
    K_val = K
    KL_val = KL

    if (L is None) and (KL_val is not None) and (K_val is not None) and not auto_K:
        auto_layers = True

    if auto_layers:
        if (KL_val is None) or (K_val is None):
            raise ValueError("auto_layers requires both KL and K.")
        if KL_val <= 1.0 or K_val <= 1.0:
            raise ValueError("Require KL>1 and K>1 for auto_layers.")
        L = max(1, int(round(math.log(KL_val) / math.log(K_val))))
        if verbose:
            log(f"[geom] auto-layers: KL={KL_val:g}, K={K_val:g} -> layers L={L}")
    elif auto_K:
        if (KL_val is None) or (L is None):
            raise ValueError("auto_K requires both KL and layers.")
        if KL_val <= 1.0 or L < 1:
            raise ValueError("Require KL>1 and layers>=1.")
        K_val = KL_val ** (1.0 / L)
        if verbose:
            log(f"[geom] auto-K: KL={KL_val:g}, L={L} -> K={K_val:.8g}")
    else:
        # Neither auto; require at least L and K
        if (L is None) or (K_val is None):
            raise ValueError("Provide layers and K, or use auto_layers (KL & K) or auto_K (KL & layers).")
        if L < 1 or K_val <= 1.0:
            raise ValueError("Require layers>=1 and K>1.")

    # ---- Mesh-size defaults from body surface ----
    if body_h is None:
        body_h_val = estimate_body_h_from_surface(knt0, ijk_body)
        if verbose:
            log(f"[size] Derived body_h (median boundary-edge): {body_h_val:.6g}")
    else:
        body_h_val = float(body_h)
        if verbose:
            log(f"[size] Using user-provided body_h: {body_h_val:.6g}")

    if h0 is None:
        if hmax is not None:
            # Derive h0 by scaling down from hmax
            h0_val = float(hmax) / (K_val ** (L * (1.0 if same_scaling else beta)))
            if verbose:
                log(f"[size] h0 not given -> derived from hmax by scaling down: h0 = hmax / K^(L*beta) = {h0_val:.6g}")
        else:
            h0_val = 1.5 * body_h_val
            if verbose:
                log(f"[size] h0 not given -> set h0 = 1.5 * body_h = {h0_val:.6g}")
    else:
        h0_val = float(h0)
        if verbose:
            log(f"[size] Using user-provided h0: {h0_val:.6g}")

    # If hmax not provided and same_scaling is requested, set hmax = h0 * (K^L)
    if (hmax is None) and same_scaling:
        hmax_val = h0_val * (K_val ** (L))
        if verbose:
            log(f"[size] same-scaling: set hmax = h0 * K^L = {hmax_val:.6g}")
    else:
        hmax_val = float(hmax) if (hmax is not None) else None

    if verbose:
        log(
            f"[info] Geometry: L={L}, K={K_val:.6g}, "
            f"KL(req)={'-' if KL_val is None else f'{KL_val:.6g}'}, "
            f"KL(achieved)={(K_val**L):.6g}"
        )
    if verbose:
        log(
            f"[info] Mesh-size: beta={1.0 if same_scaling else beta}, "
            f"h0={h0_val:.6g}, "
            f"hmax={'(derived)' if hmax_val is None else f'{hmax_val:.6g}'}"
        )
        log(
            f"[info] center=({cx},{cy},{cz}), minratio={minratio}, "
            f"max_steiner={'-' if max_steiner is None else max_steiner}, "
            f"no_exact={bool(no_exact)}"
        )

    # ---- Build shells & mesh them ----
    knt, ijk = add_shell_with_meshpy(
        knt0,
        ijk0,
        layers=L,
        K=K_val,
        beta=(1.0 if same_scaling else beta),
        center=(cx, cy, cz),
        h0=h0_val,
        hmax=hmax_val,
        minratio=minratio,
        max_steiner=max_steiner,
        no_exact=bool(no_exact),
        verbose=bool(verbose),
        same_scaling=bool(same_scaling),
        shell_type=shell_type,
    )

    # Analyze and print airbox mesh quality
    if ijk.shape[1] >= 5:
        max_mat = int(ijk[:, 4].max())
        shell_mask = ijk[:, 4] == max_mat
        tets_shell = ijk[shell_mask, :4].astype(np.int64)
        tets_core = ijk[~shell_mask, :4].astype(np.int64)
    else:
        tets_shell = ijk[:, :4]
        tets_core = np.array([])

    n_shell = tets_shell.shape[0]
    n_core = tets_core.shape[0]

    if n_shell > 0:
        shell_nids = np.unique(tets_shell)
        shell_pts = knt[shell_nids]
        mins = np.min(shell_pts, axis=0)
        maxs = np.max(shell_pts, axis=0)
        extents = maxs - mins
        vol_airbox = float(np.prod(extents))
        q_shell = compute_tet_quality(knt, tets_shell)
        q_mean, q_min = float(np.mean(q_shell)), float(np.min(q_shell))
        ext_str = f"[{extents[0]:.1f}, {extents[1]:.1f}, {extents[2]:.1f}]"

        log("\n" + "=" * 70)
        log("=== AIRBOX MESH ANALYSIS ===")
        log(f"Core Elements  : {n_core:,}")
        log(f"Shell Elements : {n_shell:,} (Total: {ijk.shape[0]:,})")
        log(f"Nodes          : {knt.shape[0]:,}")
        log(f"Airbox Extents : {ext_str}")
        log(f"Airbox Volume  : {vol_airbox:.2e}")
        log(f"Shell Quality  : Mean = {q_mean:.4f}, Min = {q_min:.4f}")
        log("=" * 70 + "\n")
    else:
        log(f"[info] No shell elements added. Core nodes = {knt.shape[0]}, elements = {ijk.shape[0]}")

    return knt, ijk


# ------------------------------ CLI (optional) ----------------------------------


def main(argv: Sequence[str] | None = None) -> None:
    """CLI entry point for adding graded shell layers.

    Parses command line arguments and invokes run_add_shell_pipeline.

    Args:
        argv: Command arguments. Uses `sys.argv` when omitted.
    """
    ap = argparse.ArgumentParser(
        prog="tommos add-shell",
        description="Add graded exterior tetrahedral layers using MeshPy/TetGen (in-memory).",
    )
    ap.add_argument(
        "--in",
        dest="in_npz",
        required=True,
        help="Input NPZ mesh containing core body 'knt' and 'ijk'.",
    )
    ap.add_argument(
        "--layers",
        type=int,
        default=None,
        help="Number of graded tetrahedral shell layers L (>= 1).",
    )
    ap.add_argument(
        "--K",
        type=float,
        default=1.5,
        help="Geometric scale factor (> 1) for the outermost shell S_L = K^L * S_0.",
    )
    ap.add_argument(
        "--KL",
        type=float,
        default=10.0,
        help="Total outermost geometric scale relative to body (> 1).",
    )
    ap.add_argument(
        "--auto-layers",
        action="store_true",
        help="Automatically compute the number of layers L given --KL and --K.",
    )
    ap.add_argument(
        "--auto-K",
        action="store_true",
        help="Automatically compute the per-layer factor K given --KL and --layers.",
    )
    ap.add_argument(
        "--beta",
        type=float,
        default=1.0,
        help="Mesh-size/geometry coupling exponent (h_l = h0 * (scale**beta)^(l+1)).",
    )
    ap.add_argument(
        "--same-scaling",
        action="store_true",
        help="Shortcut: enforce beta=1.0 and sets target hmax = h0 * K**L.",
    )
    ap.add_argument(
        "--center",
        type=str,
        default="0,0,0",
        help="Ray origin for homothetic expansion as 'cx,cy,cz' (mesh units).",
    )
    ap.add_argument(
        "--h0",
        type=float,
        default=None,
        help="Target edge length for first shell layer. Defaults to 1.5 * body_h.",
    )
    ap.add_argument(
        "--hmax",
        type=float,
        default=None,
        help="Target edge length at the outermost shell boundary (mesh units).",
    )
    ap.add_argument(
        "--body-h",
        type=float,
        default=None,
        help="Body mesh size override. If omitted, derived from surface edge length.",
    )
    ap.add_argument(
        "--minratio",
        type=float,
        default=1.4,
        help="TetGen quality minratio (-q) for shell tetrahedra.",
    )
    ap.add_argument(
        "--max-steiner",
        type=int,
        default=None,
        help="Limit Steiner points added by TetGen (-S#).",
    )
    ap.add_argument("--no-exact", action="store_true", help="Suppress TetGen exact arithmetic (-X).")
    ap.add_argument("--verbose", action="store_true", help="Enable verbose TetGen output.")
    ap.add_argument(
        "--shell-type",
        type=str,
        default="hull",
        choices=["triangles", "hull"],
        help="Outer shell boundary type: copy original 'triangles' or use convex 'hull' (default).",
    )

    # NEW: optional VTU export of the merged (body + shells) mesh
    ap.add_argument(
        "--out-npz",
        type=str,
        default=None,
        help="Optional path to save the merged mesh as an NPZ file.",
    )
    ap.add_argument(
        "--out-vtu",
        type=str,
        default=None,
        help="Optional path to save the merged mesh as a VTU file for visualization.",
    )

    args = ap.parse_args(argv)

    knt, ijk = run_add_shell_pipeline(
        in_npz=args.in_npz,
        layers=args.layers,
        K=args.K,
        KL=args.KL,
        auto_layers=bool(args.auto_layers),
        auto_K=bool(args.auto_K),
        beta=float(args.beta),
        same_scaling=bool(args.same_scaling),
        center=args.center,  # string "cx,cy,cz" is accepted
        h0=args.h0,
        hmax=args.hmax,
        body_h=args.body_h,
        minratio=float(args.minratio),
        max_steiner=args.max_steiner,
        no_exact=bool(args.no_exact),
        verbose=bool(args.verbose),
        shell_type=args.shell_type,
    )
    print(f"[ok] merged in-memory mesh: nodes={knt.shape[0]:,}, tets={ijk.shape[0]:,}")

    # Optional VTU export
    if args.out_vtu:
        out_vtu = str(Path(args.out_vtu).with_suffix(".vtu"))
        cells = [("tetra", ijk[:, :4].astype(np.int32))]
        cell_data = {"mat_id": [ijk[:, 4].astype(np.int32)]}
        meshio.Mesh(points=knt.astype(np.float64), cells=cells, cell_data=cell_data).write(out_vtu)
        print(f"[ok] wrote VTU -> {out_vtu}")

    if args.out_npz:
        out_npz = str(Path(args.out_npz).with_suffix(".npz"))
        np.savez(out_npz, knt=knt.astype(np.float64), ijk=ijk.astype(np.int32))


if __name__ == "__main__":
    main()
