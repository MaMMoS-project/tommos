def estimate_body_h_from_surface(knt: np.ndarray, ijk_with_mat: np.ndarray) -> float:
    """Estimate surface mesh size as the median boundary-edge length.

    Args:
        knt (np.ndarray): node coordinates.
        ijk_with_mat (np.ndarray): tetrahedron connectivity.

    Returns:
        float: median edge length.
    """
    tris = find_outer_surface_tris(ijk_with_mat)
    if tris.size == 0:
        diag = np.linalg.norm(knt.max(0) - knt.min(0))
        return max(1e-6, 0.02 * diag)

    edges = np.vstack(
        [
            np.sort(tris[:, [0, 1]], axis=1),
            np.sort(tris[:, [1, 2]], axis=1),
            np.sort(tris[:, [2, 0]], axis=1),
        ]
    )
    edges = np.unique(edges, axis=0)
    p = knt[edges[:, 0]]
    q = knt[edges[:, 1]]
    lens = np.linalg.norm(q - p, axis=1)
    return max(float(np.median(lens)), 1e-12)


def subdivide_flat_mesh(V: np.ndarray, F: np.ndarray, levels: int) -> tuple[np.ndarray, np.ndarray]:
    """Subdivide flat triangles into 4 similar triangles by inserting midpoints on all edges.

    Args:
        V (np.ndarray): Node coordinates (Nv, 3).
        F (np.ndarray): Triangle connectivity (Nf, 3).
        levels (int): Number of subdivision levels.

    Returns:
        tuple[np.ndarray, np.ndarray]: (Subdivided vertices, Subdivided faces).
    """
    for _ in range(max(0, levels)):
        edge_cache = {}
        new_faces = []
        new_verts = V.tolist()

        def mid_idx(i: int, j: int) -> int:
            key = (i, j) if i < j else (j, i)
            if key in edge_cache:  # noqa: B023
                return edge_cache[key]  # noqa: B023
            vi, vj = np.array(new_verts[i]), np.array(new_verts[j])  # noqa: B023
            vm = 0.5 * (vi + vj)
            new_verts.append(vm.tolist())  # noqa: B023
            idx = len(new_verts) - 1  # noqa: B023
            edge_cache[key] = idx  # noqa: B023
            return idx

        for i, j, k in F:
            a = mid_idx(i, j)
            b = mid_idx(j, k)
            c = mid_idx(k, i)
            new_faces.extend(
                [
                    [i, a, c],
                    [a, j, b],
                    [c, b, k],
                    [a, b, c],
                ]
            )
        V = np.array(new_verts, dtype=np.float64)
        F = np.array(new_faces, dtype=np.int32)
    return V, F


# ------------------------------- PLC builders -------------------------------
def build_layer_nodes(
    knt0: np.ndarray, surf_verts: np.ndarray, center: np.ndarray, K: float, layers: int
) -> tuple[np.ndarray, dict[tuple[int, int], int], list[np.ndarray]]:
    """Create node copies for each surface vertex across layers.

    Geometric scales are K**layer_idx.

    Args:
        knt0 (np.ndarray): original body nodes.
        surf_verts (np.ndarray): indices of nodes on the outer surface.
        center (np.ndarray): ray origin for scaling.
        K (float): geometric growth factor (> 1).
        layers (int): number of shell layers.

    Returns:
        tuple: (All nodes, node map (vid, layer) -> id, list of scaling vectors).
    """
    knt = knt0.copy()

    vmin = np.min(knt0, axis=0)
    vmax = np.max(knt0, axis=0)
    ext = vmax - vmin
    Lmax = float(np.max(ext))

    node_map: dict[tuple[int, int], int] = {}

    for vid in surf_verts:
        node_map[(int(vid), 0)] = int(vid)

    c = center.reshape(1, 3)
    v0 = knt0[surf_verts] - c  # rays from center to surface verts

    max_anisotropy = 5.0

    # Print header once (before your loop)
    print(f"{'Layer':>5} | {'sx':>10} | {'sy':>10} | {'sz':>10}")
    print("-" * 5 + "-+-" + "-" * 10 + "-+-" + "-" * 10 + "-+-" + "-" * 10)

    svecs_layer = []
    for layer_idx in range(1, layers + 1):
        s = K**layer_idx
        t = layer_idx / layers if layers > 1 else 1.0
        L_target = s * Lmax
        sx = np.array([L_target / ext[0], L_target / ext[1], L_target / ext[2]], dtype=float)
        sv = (1 - t) * np.array([1.0, 1.0, 1.0]) + t * sx

        ext_layer = ext * sv
        r = ext_layer.max() / max(ext_layer.min(), 1e-12)
        if r > max_anisotropy:
            # softly clamp: scale towards the geometric mean
            g = np.exp(np.log(ext_layer).mean())
            # blend towards isotropy keeping product constant
            alpha = r / max_anisotropy  # >1
            ext_layer = g * (ext_layer / g) ** (1.0 / alpha)
            sv = ext_layer / ext

        # pts = c + s * v0
        print(f"{layer_idx:5d} | {sv[0]:10.6f} | {sv[1]:10.6f} | {sv[2]:10.6f}")
        pts = c + v0 * sv.reshape(1, 3)
        start = knt.shape[0]
        knt = np.vstack([knt, pts])
        for i, vid in enumerate(surf_verts):
            node_map[(int(vid), layer_idx)] = start + i

        svecs_layer.append(sv.copy())

    return knt, node_map, svecs_layer


def make_shell_plc_from_surface(  # noqa: D417
    knt0: np.ndarray,
    tris0: np.ndarray,
    layers: int,
    K: float,
    center: tuple[float, float, float],
    shell_type: str = "box",
    target_h: float | None = None,
) -> tuple[np.ndarray, list[list[int]], np.ndarray, np.ndarray, dict, list]:
    """Build a TetGen PLC with nested homothetic surfaces for shell meshing.

    Args:
        knt0: body nodes.
        tris0: body surface triangles.
        layers: number of layers.
        K: per-layer scale.
        center: ray origin.
        shell_type: 'triangles', 'hull', or 'box'.
        target_h: target mesh size.

    Returns:
        tuple: (All nodes, facets, seeds, surface vertex indices, node map,
                scaling vectors).
    """
    center = np.asarray(center, dtype=np.float64)
    tris0 = np.sort(tris0.astype(np.int64), axis=1)
    surf_verts = np.unique(tris0.reshape(-1))

    if shell_type in ("hull", "box"):
        if shell_type == "hull":
            from scipy.spatial import ConvexHull

            hull = ConvexHull(knt0)
            hull_verts_orig = np.unique(hull.simplices.reshape(-1))
            hull_V = knt0[hull_verts_orig].copy()
            old_to_new = {old: new for new, old in enumerate(hull_verts_orig)}
            hull_F = np.array([[old_to_new[v] for v in tri] for tri in hull.simplices], dtype=np.int32)
        else:  # box
            vmin = np.min(knt0, axis=0)
            vmax = np.max(knt0, axis=0)
            hull_V = np.array(
                [
                    [vmin[0], vmin[1], vmin[2]],
                    [vmax[0], vmin[1], vmin[2]],
                    [vmax[0], vmax[1], vmin[2]],
                    [vmin[0], vmax[1], vmin[2]],
                    [vmin[0], vmin[1], vmax[2]],
                    [vmax[0], vmin[1], vmax[2]],
                    [vmax[0], vmax[1], vmax[2]],
                    [vmin[0], vmax[1], vmax[2]],
                ],
                dtype=np.float64,
            )
            hull_F = np.array(
                [
                    [0, 2, 1],
                    [0, 3, 2],
                    [4, 5, 6],
                    [4, 6, 7],
                    [0, 1, 5],
                    [0, 5, 4],
                    [2, 3, 7],
                    [2, 7, 6],
                    [1, 2, 6],
                    [1, 6, 5],
                    [3, 0, 4],
                    [3, 4, 7],
                ],
                dtype=np.int32,
            )

        # Compute subdivision levels
        levels = 0
        if target_h is not None and target_h > 0:
            edges = np.vstack([hull_F[:, [0, 1]], hull_F[:, [1, 2]], hull_F[:, [2, 0]]])
            lens = np.linalg.norm(hull_V[edges[:, 1]] - hull_V[edges[:, 0]], axis=1)
            avg_len = np.mean(lens)
            desired_len = target_h * 2.0  # Allow some coarseness
            if avg_len > desired_len:
                levels = int(np.ceil(np.log2(avg_len / desired_len)))
                levels = min(levels, 4)  # Cap at 4 levels (256x triangles) to prevent explosion

        hull_V, hull_F = subdivide_flat_mesh(hull_V, hull_F, levels)
        hull_verts = np.arange(len(hull_V))
        hull_tris = hull_F

        # Build node map & scaling copy for layers 1..L using hull_verts
        knt_all = knt0.copy()
        node_map: dict[tuple[int, int], int] = {}
        for vid in surf_verts:
            node_map[(int(vid), 0)] = int(vid)

        vmin = np.min(knt0, axis=0)
        vmax = np.max(knt0, axis=0)
        ext = vmax - vmin
        Lmax = float(np.max(ext))
        c = center.reshape(1, 3)
        v0 = hull_V - c  # rays from center to hull vertices

        max_anisotropy = 5.0
        svecs_layer = []

        print(f"{'Layer':>5} | {'sx':>10} | {'sy':>10} | {'sz':>10}")
        print("-" * 5 + "-+-" + "-" * 10 + "-+-" + "-" * 10 + "-+-" + "-" * 10)

        for layer_idx in range(1, layers + 1):
            s = K**layer_idx
            t = layer_idx / layers if layers > 1 else 1.0
            L_target = s * Lmax
            sx = np.array([L_target / ext[0], L_target / ext[1], L_target / ext[2]], dtype=float)
            sv = (1 - t) * np.array([1.0, 1.0, 1.0]) + t * sx

            ext_layer = ext * sv
            r = ext_layer.max() / max(ext_layer.min(), 1e-12)
            if r > max_anisotropy:
                g = np.exp(np.log(ext_layer).mean())
                alpha = r / max_anisotropy
                ext_layer = g * (ext_layer / g) ** (1.0 / alpha)
                sv = ext_layer / ext

            print(f"{layer_idx:5d} | {sv[0]:10.6f} | {sv[1]:10.6f} | {sv[2]:10.6f}")
            pts = c + v0 * sv.reshape(1, 3)
            start = knt_all.shape[0]
            knt_all = np.vstack([knt_all, pts])
            for i, vid in enumerate(hull_verts):
                node_map[(int(vid), layer_idx)] = start + i

            svecs_layer.append(sv.copy())

        # Build facets
        facets: list[list[int]] = []
        # Layer 0 uses the original surface triangles
        for tri in tris0:
            v = [node_map[(int(tri[0]), 0)], node_map[(int(tri[1]), 0)], node_map[(int(tri[2]), 0)]]
            facets.append(v)
        # Layers 1..L use the scaled convex hull triangles
        for layer_idx in range(1, layers + 1):
            for tri in hull_tris:
                v = [
                    node_map[(int(tri[0]), layer_idx)],
                    node_map[(int(tri[1]), layer_idx)],
                    node_map[(int(tri[2]), layer_idx)],
                ]
                facets.append(v)

        # Build seeds:
        seeds = []
        # Region 0: between layer 0 (tris0) and layer 1 (hull_tris)
        tri0 = tris0[0]
        ctr0 = knt0[tri0].mean(axis=0)
        sv1 = svecs_layer[0]
        ctr1 = c.ravel() + (ctr0 - c.ravel()) * sv1
        seeds.append(0.5 * (ctr0 + ctr1))

        # Subsequent regions: between hull layer l and l+1
        hull_tri0 = hull_tris[0]

        def hull_centroid_at(layer: int) -> np.ndarray:
            vids = [node_map[(int(v), layer)] for v in hull_tri0]
            return knt_all[vids].mean(axis=0)

        for layer_idx in range(1, layers):
            seeds.append(0.5 * (hull_centroid_at(layer_idx) + hull_centroid_at(layer_idx + 1)))

        seeds = np.vstack(seeds).astype(np.float64)

    else:
        # Standard: copy original surface triangles to each scaled layer
        knt_all, node_map, svecs_layer = build_layer_nodes(knt0, surf_verts, center, K, layers)

        facets: list[list[int]] = []
        for layer_idx in range(0, layers + 1):
            for tri in tris0:
                v = [
                    node_map[(int(tri[0]), layer_idx)],
                    node_map[(int(tri[1]), layer_idx)],
                    node_map[(int(tri[2]), layer_idx)],
                ]
                facets.append(v)

        tri0 = tris0[0]

        def centroid_at(layer: int) -> np.ndarray:
            vids = [node_map[(int(v), layer)] for v in tri0]
            return knt_all[vids].mean(axis=0)

        seeds = np.vstack(
            [0.5 * (centroid_at(layer_idx) + centroid_at(layer_idx + 1)) for layer_idx in range(layers)]
        ).astype(np.float64)

    # Optional sanity check:
    assert seeds.shape == (layers, 3)

    return knt_all, facets, seeds, surf_verts, node_map, svecs_layer


